"""[Recovery change] 把已核验的专家接管分支导出为训练专用纠偏数据；不改原NPZ。"""
from datetime import datetime
import hashlib
import json
from pathlib import Path

import numpy as np
from robotnik_bodyframe_features import BODYFRAME_FEATURE_VERSION

BASELINE = 'bc_training_arm_ring_r08_aux_b2_control/run_20261104_025706_206181'
RUN_ROOT = 'bc_training_arm_ring_r08_recovery'
SCHEMA = 'expert_recovery_pre_action_bodyframe26_arm7_v1'
FROZEN = ('best_model.pt', 'normalization.npz', 'config.json', 'data_split.json')


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read_json(path):
    return json.loads(Path(path).read_text(encoding='utf-8'))


def write_json(path, value):
    path = Path(path)
    tmp = path.with_suffix(path.suffix + '.tmp')
    tmp.write_text(json.dumps(value, indent=2, ensure_ascii=False, allow_nan=False), encoding='utf-8')
    tmp.replace(path)


def target_key(target):
    return tuple(np.round(np.asarray(target, dtype=float), 6))


def check_train_target(split, target):
    key = target_key(target)
    if key not in {target_key(t) for t in split['targets']['train']}:
        raise ValueError(f'Recovery target is not TRAIN: {target}')
    if any(key in {target_key(t) for t in split['targets'][part]} for part in ('val', 'test')):
        raise ValueError(f'Target leaks into held-out split: {target}')


def export_diagnostics(diagnostic_dir, parent, destination):
    """只导出专家独自恢复且连续保持成功的分支；保留原诊断文件。"""
    diagnostic_dir, parent, destination = map(lambda p: Path(p).resolve(), (diagnostic_dir, parent, destination))
    summary = read_json(diagnostic_dir/'summary.json')
    if (summary.get('diagnostic_only') is not True or summary['process_errors'] != 0
            or summary['processed_cases'] != summary['planned_cases']):
        raise ValueError('Collection must be complete and free of process errors before export')
    split = read_json(parent/'data_split.json')
    entries = []
    candidates = [r for r in summary['results'] if r.get('category') == 'expert_only_recovered_and_held']
    if not candidates:
        raise ValueError('No expert-only successful recoveries; no empty dataset exported')
    destination.mkdir(parents=True, exist_ok=False)
    for row in candidates:
        report_path = Path(row['report']).resolve()
        report = read_json(report_path)
        if (Path(report['arm_run']).resolve() != parent or report['target_owner'] != 'train'
                or report['category'] != row['category'] or not report['state_and_rng_restored_for_each_branch']
                or report['hold_seconds'] < 1 or report['true_reach_tolerance_m'] != .01
                or report['sensor_noise'] != 'config' or not all(report['sensor_noise_enabled'])):
            raise ValueError('Wrong source, ownership, noise or recovery acceptance rule')
        check_train_target(split, report['target'])
        for p, expected in report['source_hashes'].items():
            if sha256(p) != expected:
                raise ValueError(f'Diagnostic source/config changed: {p}')
        if report['source_hashes'].get(str(parent/'best_model.pt')) != sha256(parent/'best_model.pt'):
            raise ValueError('Diagnostic was generated by different parent weights')
        branch_path = report_path.with_name('expert_continuation.npz')
        with np.load(branch_path, allow_pickle=False) as data:
            obs, action, times = data['observations'], data['actions'], data['timestamps']
            n = len(action)
            if (n < 1 or obs.shape != (n, 26) or action.shape != (n, 11) or times.shape != (n+1,)
                    or not np.all(data['action_source'] == 'expert') or not np.all(np.diff(times) > 0)
                    or not np.isfinite(obs).all() or not np.isfinite(action).all()
                    or not np.isin(obs[:, 22], [0, 1]).all()):
                raise ValueError('Misaligned, nonfinite or mixed-label recovery trace')
            np.testing.assert_allclose(data['target'], report['target'], atol=1e-6, rtol=0)
            # [Recovery alignment] states是N+1，actions是N；仅取动作前的前N帧，绝不错移一帧。
            errors = data['ee_errors']; end = times[-1]
            if not np.all(errors[times >= end-1-1e-9] < .01):
                raise ValueError('Expert did not continuously hold true EE within 1cm for 1s')
            if (np.max(np.abs(action[:, :4])) > 3+1e-6
                    or np.max(np.abs(action[:, 4:])) > 30+1e-6):
                raise ValueError('Applied actions exceed diagnostic bounds')
            filename = f'recovery_{len(entries)+1:04d}.npz'
            np.savez_compressed(destination/filename,
                observations=obs.astype(np.float32), arm_torques=action[:, 4:11].astype(np.float32),
                timestamps=times[:-1], target=data['target'],
                observed_ee_positions=data['observed_ee_positions'][:-1],
                true_ee_positions=data['ee_positions'][:-1],
                feature_version=BODYFRAME_FEATURE_VERSION, schema=SCHEMA,
                target_owner='train', action_source='expert_arm_controller',
                inputs_normalized=False, true_state_used_for_control=False,
                # 车轮由导航模型产生，不作为新训练标签，机械臂输出只取后7维。
                navigation_training_labels_included=False)
        entries.append({'file':filename, 'sha256':sha256(destination/filename), 'frames':n,
            'target':report['target'], 'seed':report['seed'], 'train_index':report['train_index'],
            'source_report':str(report_path), 'source_report_sha256':sha256(report_path),
            'source_trace':str(branch_path), 'source_trace_sha256':sha256(branch_path)})
    manifest = {'schema':SCHEMA, 'created_at':datetime.now().isoformat(), 'target_owner':'train',
        'feature_version':BODYFRAME_FEATURE_VERSION, 'input_dim':26, 'arm_output_dim':7,
        'parent_arm_run':str(parent), 'parent_sha256':{n:sha256(parent/n) for n in FROZEN},
        'diagnostics_dir':str(diagnostic_dir), 'diagnostics_summary_sha256':sha256(diagnostic_dir/'summary.json'),
        'acceptance':'expert_only_true_distance_lt_1cm_continuous_hold_ge_1s',
        'model_prefix_used_as_labels':False, 'true_position_used_as_input':False,
        'trajectories':len(entries), 'frames':sum(e['frames'] for e in entries), 'entries':entries}
    write_json(destination/'recovery_manifest.json', manifest)
    return manifest


def load_recovery(manifest_path, parent, split, stats):
    """[Recovery training] 独立26维输入已由采集器转换，不得再次做23→26转换。"""
    manifest_path, parent = Path(manifest_path).resolve(), Path(parent).resolve()
    manifest = read_json(manifest_path)
    if (manifest.get('schema') != SCHEMA or manifest.get('feature_version') != BODYFRAME_FEATURE_VERSION
            or manifest.get('target_owner') != 'train' or Path(manifest['parent_arm_run']).resolve() != parent):
        raise ValueError('Recovery schema/parent mismatch')
    if manifest['parent_sha256'] != {n:sha256(parent/n) for n in FROZEN}:
        raise ValueError('Recovery data belongs to different frozen baseline/split')
    xs, ys, lows = [], [], []
    for entry in manifest['entries']:
        check_train_target(split, entry['target'])
        p = (manifest_path.parent/entry['file']).resolve()
        if p.parent != manifest_path.parent or sha256(p) != entry['sha256']:
            raise ValueError('Recovery file location/content changed')
        with np.load(p, allow_pickle=False) as d:
            x, y, t = d['observations'], d['arm_torques'], d['timestamps']
            n = entry['frames']
            if (x.shape != (n, 26) or y.shape != (n, 7) or t.shape != (n,)
                    or not np.isfinite(x).all() or not np.isfinite(y).all()
                    or not np.all(np.diff(t) > 0) or not np.isin(x[:, 22], [0, 1]).all()
                    or str(d['action_source']) != 'expert_arm_controller' or bool(d['inputs_normalized'])
                    or bool(d['true_state_used_for_control']) or str(d['schema']) != SCHEMA):
                raise ValueError('Recovery fields invalid')
            np.testing.assert_allclose(d['target'], entry['target'], atol=1e-6, rtol=0)
            # 高度使用世界target元数据，不能误用26维输入的局部target-z。
            xs.append(((x-stats['x_mean'])/stats['x_std']).astype(np.float32))
            ys.append(((y-stats['y_mean'][4:11])/stats['y_std'][4:11]).astype(np.float32))
            lows.append(np.full(n, entry['target'][2] <= .35+1e-6))
    if not xs or sum(len(x) for x in xs) != manifest['frames']:
        raise ValueError('Empty/incomplete recovery data')
    return np.concatenate(xs), np.concatenate(ys), np.concatenate(lows), manifest
